// 순서: 예제 실행 → 1단계 → 2단계 → 3단계. 단계마다 저장·실행해서 [예상 출력]과 비교해요.

void main() {
  example();
  step1();
  step2();
   step3();  //← 3단계 [내 예측]을 다 적은 뒤에 앞의 // 를 지우세요.
}

// ━━━━━━━━━━ 예제 ━━━━━━━━━━
void example() {
  print('--- 예제 ---');
  final age = <String, int>{'콩이': 3};
  age['콩이'] = 4;
  age['보리'] = 1;
  print(age);
  print(age.length);
}
// [한 줄씩 읽기]
// 1. age['콩이'] = 4;  → '콩이' 이름표가 이미 있어서 값이 3에서 4로 바뀌어요.
// 2. age['보리'] = 1;  → '보리' 이름표가 없어서 새로 들어가요.
//    모양은 같아요. 이름표가 있으면 바꾸고, 없으면 새로 넣어요.
// 3. print(age)처럼 Map 전체를 출력하면 {콩이: 4, 보리: 1}처럼 따옴표 없이 보여요. 넣은 순서대로 나와요.
// 4. age.length는 이름표·값 쌍의 개수예요. List의 length와 같아요.
// (final로 만든 Map도 안의 값은 바꿀 수 있어요. final은 age에 다른 Map을 통째로 다시 넣지 못한다는 뜻이에요.)
// [예제 출력]
// --- 예제 ---
// {콩이: 4, 보리: 1}
// 2

// ━━━━━━━━━━ 1단계: 따라 하기 ━━━━━━━━━━
// [할 일] step1 안에, 예제와 같은 모양으로 쓰기
//   ① weekKm Map을 만들기:  '월' → 3,  '수' → 5,  '금' → 4   (어제 1단계와 같아요)
//   ② 수요일 값을 7로 바꾸기
//   ③ '일' 이름표에 2를 새로 넣기
//   ④ weekKm 전체를 출력
// [예상 출력]
// --- 1단계 ---
// {월: 3, 수: 7, 금: 4, 일: 2}

void step1() {
  print('--- 1단계 ---');
  final weekKm = <String, int>{'월': 3, '수': 5, '금': 4};
  weekKm['수'] = 7;
  weekKm['일'] = 2;
  print(weekKm);
  // 여기에 쓰기
}

// ━━━━━━━━━━ 2단계: 직접 작성 ━━━━━━━━━━
// [새 내용] 빈 Map으로 시작하기
//   final 이름 = <String, int>{};   ← { } 안이 비어 있어요
//   빈 Map은 < > 종류를 꼭 적어요. 들어 있는 값이 없어서 Dart가 종류를 알 수 없기 때문이에요.
// [할 일] step2 안에 쓰기
//   ① 이름표는 글자, 값은 정수인 빈 Map cart를 만들기 (장바구니)
//   ② '우유'를 2개, '빵'을 1개 넣기
//   ③ cart의 개수(쌍의 수)를 출력
//   ④ cart 전체를 출력
// [예상 출력]
// --- 2단계 ---
// 2
// {우유: 2, 빵: 1}

void step2() {
  print('--- 2단계 ---');
  final cart = <String, int>{};
  cart['우유'] = 2;
  cart['빵'] = 1;
  print(cart.length);
  print(cart);
  // 여기에 쓰기
}

// ━━━━━━━━━━ 3단계: 읽고 예측 ━━━━━━━━━━
// 아래 step3은 이미 완성된 코드예요. 고치지 말고 읽기만 해요.
// seats는 자리 번호(이름표)에 앉은 사람 이름(값)이에요.
// [할 일]
//   ① 실행하기 전에 [내 예측]에 출력 세 줄을 적기
//   ② main의 // step3(); 에서 // 를 지우고 실행해서 비교
// [내 예측]
// --- 3단계 ---
//2
//하늘
//{A1: 하늘, A2: 지우}

void step3() {
  print('--- 3단계 ---');
  final seats = <String, String>{'A1': '민수'};
  seats['A2'] = '지우';
  seats['A1'] = '하늘';
  print(seats.length);
  print(seats['A1']);
  print(seats);
}

// [내 말로 설명]
// seats['A1'] = '하늘'; 줄이 실행되기 전과 후에 seats의 개수는 왜 그대로일까요?
