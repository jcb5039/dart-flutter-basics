// 순서: 예제 실행 → 1단계 → 2단계 → 3단계. 단계마다 저장·실행해서 [예상 출력]과 비교해요.

void main() {
  example();
  step1();
  step2();
   step3(); // ← 3단계 [내 예측]을 다 적은 뒤에 앞의 // 를 지우세요.
}

// ━━━━━━━━━━ 예제 ━━━━━━━━━━
void example() {
  print('--- 예제 ---');
  final age = <String, int>{'콩이': 3, '나비': 5};
  print(age['나비']);
  print(age['보리']);
}
// [한 줄씩 읽기]
// 1. <String, int>: 이름표는 글자(String), 값은 정수(int)예요.
//    그래서 이름표 '콩이'에는 따옴표가 있고, 값 3에는 따옴표가 없어요.
// 2. age['나비']는 '나비' 이름표의 값 5를 꺼내요.
// 3. age['보리']처럼 없는 이름표로 꺼내면 오류가 아니라 null이 나와요. null은 "값 없음"이라는 뜻이에요.
//    (List는 없는 번호 list[9]로 꺼내면 오류로 멈춰요. Map은 멈추지 않고 null을 줘요.)
// [예제 출력]
// --- 예제 ---
// 5
// null

// ━━━━━━━━━━ 1단계: 따라 하기 ━━━━━━━━━━
// [할 일] step1 안에, 예제의 age와 같은 모양으로 쓰기
//   ① weekKm라는 Map을 만들기. 이름표는 요일 글자, 값은 달린 km(정수)
//        '월' → 3,  '수' → 5,  '금' → 4
//   ② 수요일 값을 출력
// [예상 출력]
// --- 1단계 ---
// 5

void step1() {
  print('--- 1단계 ---');
  final weekKm = <String, int>{'월': 3, '수': 5, '금': 4};
  print(weekKm['수']);
  // 여기에 쓰기
}

// ━━━━━━━━━━ 2단계: 직접 작성 ━━━━━━━━━━
// [할 일] step2 안에 쓰기
//   ① score라는 Map을 만들기. 이름표는 과목, 값은 점수(정수)
//        '국어' → 90,  '수학' → 85
//   ② 수학 점수를 출력
//   ③ 영어 점수를 출력 (Map에 영어는 없어요. 무엇이 나오는지 확인해요)
// [예상 출력]
// --- 2단계 ---
// 85
// null

void step2() {
  print('--- 2단계 ---');
  final score = <String, int>{'국어': 90, '수학': 85};
  print(score['수학']);
  print(score['영어']);
  // 여기에 쓰기
}

// ━━━━━━━━━━ 3단계: 읽고 예측 ━━━━━━━━━━
// 아래 step3은 이미 완성된 코드예요. 고치지 말고 읽기만 해요.
// stock은 가게에 남은 과일 개수예요. '배'는 이름표는 있지만 0개 남았어요.
// [할 일]
//   ① 실행하기 전에 [내 예측]에 출력 세 줄을 적기
//   ② main의 // step3(); 에서 // 를 지우고 실행해서 비교
// [내 예측]
// --- 3단계 ---
//0
//null
//3

void step3() {
  print('--- 3단계 ---');
  final stock = <String, int>{'사과': 3, '배': 0};
  print(stock['배']);
  print(stock['감']);
  print(stock['사과']);
}

